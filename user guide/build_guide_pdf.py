def H1(n, text):
    return Paragraph(f"{n}.  {text}", h1)

def B(text):
    return Paragraph(text, bullet, bulletText="\u2022")

def S(text):
    return Paragraph(f"<b>{text}</b>", step)

def img_cell(name, width=150):
    path = os.path.join(SHOTS, name)
    # 414x880 source -> proportional height
    h = width * 880.0 / 414.0
    return Image(path, width=width, height=h)

def feature_section(num, title, image, caption_text, paragraphs, steps=None, tip_text=None, bullets=None):
    """Side-by-side layout: phone screenshot left, guidance right.

    Heading + table + caption are one KeepTogether unit: a screenshot block is
    over half a page tall, so letting the heading separate strands it at a page
    bottom with nothing after it.
    """
    heading = H1(num, title)
    text_flow = []
    for p in paragraphs:
        text_flow.append(Paragraph(p, body))
    if steps:
        for s_ in steps:
            text_flow.append(S(s_))
    if bullets:
        for b_ in bullets:
            text_flow.append(B(b_))
    if tip_text:
        text_flow.append(Spacer(1, 2))
        text_flow.append(Paragraph(f"<b>Tip:</b> {tip_text}", tip))

    img = img_cell(image)
    cap = Paragraph(caption_text, caption)
    row = [[img, text_flow]]
    t = Table(row, colWidths=[160, CONTENT_W - 160 - 14])
    t.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (0, -1), 0),
        ("RIGHTPADDING", (0, 0), (0, -1), 6),
        ("LEFTPADDING", (1, 0), (1, -1), 10),
        ("RIGHTPADDING", (1, 0), (1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    t.hAlign = "CENTER"
    return [KeepTogether([heading, t, cap])]

