# ---- Build ----
def on_page(canvas, doc):
    canvas.saveState()
    canvas.setFont("Calibri", 8)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, 30, "MyGym User Guide")
    canvas.drawRightString(PAGE_W - MARGIN, 30, f"Page {doc.page + 1}")
    canvas.setStrokeColor(BG_SURFACE)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 42, PAGE_W - MARGIN, 42)
    canvas.restoreState()

doc = BaseDocTemplate(
    os.path.join(BASE, "_body.pdf"), pagesize=A4,
    leftMargin=MARGIN, rightMargin=MARGIN, topMargin=54, bottomMargin=56,
    title="MyGym User Guide", author="Z.ai",
)
frame = Frame(MARGIN, 56, CONTENT_W, PAGE_H - 54 - 56, id="main")
doc.addPageTemplates([PageTemplate(id="page", frames=[frame], onPage=on_page)])
doc.build(story)
